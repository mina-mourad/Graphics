float Text::Width(const std::string& s, float px)
{
    if (s.empty()) return 0.0f;
    return (6.0f * static_cast<float>(s.size()) - 1.0f) * px;
}

void Text::Draw(const std::string& s, glm::vec2 pos, float px, glm::vec3 color,
                Align align, float alpha)
{
    float x = pos.x;
    float w = Width(s, px);
    if (align == Align::Center) x -= w * 0.5f;
    else if (align == Align::Right) x -= w;

    for (char ch : s) {
        const Glyph* g = Find(ch);
        if (g) {
            for (int row = 0; row < 7; ++row) {
                const char* r = g->rows[row];
                int col = 0;
                while (col < 5) {
                    if (r[col] != '#') { ++col; continue; }
                    int start = col;
                    while (col < 5 && r[col] == '#') ++col;
                    float runW = static_cast<float>(col - start) * px;
                    float cx = x + static_cast<float>(start) * px + runW * 0.5f;
                    float cy = pos.y + static_cast<float>(6 - row) * px + px * 0.5f;
                    Renderer2D::DrawQuadRot(glm::vec2(cx, cy), glm::vec2(runW, px), 0.0f, color, alpha);
                }
            }
        }
        x += 6.0f * px;
    }
}

void Text::DrawShadow(const std::string& s, glm::vec2 pos, float px, glm::vec3 color,
                      Align align, float alpha)
{
    Draw(s, pos + glm::vec2(px * 0.8f, -px * 0.8f), px, glm::vec3(0.05f, 0.03f, 0.02f), align, alpha * 0.85f);
    Draw(s, pos, px, color, align, alpha);
}
